// Headless driver for index.html?fake: visits every screen and asks tools/check.mjs (--shotq) for a screenshot of each.
(async () => {
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const until = async (fn, ms = 30000) => { const t = Date.now(); while (!fn()) { if (Date.now() - t > ms) throw new Error(`timeout in ${owl.scene}`); await sleep(50); } };
  const q = (window.shotQueue = []);
  let taken = 0;
  const shot = async (name) => { q.push(name); taken++; await until(() => window.shotsTaken === taken); };
  const said = (msg) => owl.log.some((l) => l[1].startsWith(msg));
  const face = (window.fakeFace = { deny: true });
  await until(() => owl.scene === "Title");
  await sleep(600); await shot("1-title");
  owl.press("play");
  await sleep(400); await shot("2-explain");
  owl.press("camera");
  await until(() => owl.scene === "Denied");
  await sleep(400); await shot("3-denied");
  delete face.deny;
  owl.press("retry");
  await sleep(100); owl.press("camera");
  await until(() => owl.scene === "Calibrate");
  await sleep(400); await shot("4-calib");
  owl.press("calibrate");
  await sleep(2300); face.blinkL = face.blinkR = 0.9; await sleep(300); face.blinkL = face.blinkR = 0.08;
  await sleep(900); face.smile = 0.8; await shot("5-calib-smile"); await sleep(300); face.smile = 0.03;
  await until(() => owl.scene === "Match");
  await sleep(900); await shot("6-countdown");
  await until(() => said("stare"));
  await sleep(300); owl.trick("face"); await sleep(250); await shot("7-trick-face");
  await sleep(1500); owl.trick("feathers"); await sleep(900); await shot("8-trick-feathers");
  await until(() => said("end")); await sleep(500); await shot("9-win");
  await until(() => owl.scene === "Result"); await sleep(500); await shot("10-result-win");
  owl.press("again");
  await until(() => owl.log.filter((l) => l[1] === "stare").length === 2);
  await sleep(2000); face.smile = 0.9;
  await until(() => owl.log.filter((l) => l[1].startsWith("end")).length === 2); await sleep(500); await shot("11-lose");
  face.smile = 0.03;
  await until(() => owl.scene === "Result"); await sleep(500); await shot("12-result-lose");
  return owl.log.map((l) => l[1]).join(" | ");
})();
